import sqlite3
import json
import random
from faker import Faker

# Use the Philippine locale to generate localized names and addresses if possible,
# falling back to US for generic data.
fake = Faker(['en_PH', 'en_US'])

DB_PATH = 'pds_records.db'
DEPARTMENTS = ['Human Resources', 'IT Department', 'Finance', 'Operations', 'Marketing', 'Legal']

def generate_mock_db(num_records=35):
    conn = sqlite3.connect(DB_PATH)
    cursor = conn.cursor()

    # 1. Populate the departments table
    for dept in DEPARTMENTS:
        cursor.execute('INSERT OR IGNORE INTO departments (name) VALUES (?)', (dept,))

    # 2. Get all existing columns from the employees table dynamically
    cursor.execute("PRAGMA table_info(employees)")
    # Filter out 'id' and 'date_created' as they are auto-generated by the database
    columns = [row[1] for row in cursor.fetchall() if row[1] not in ('id', 'date_created')]

    print(f"Generating {num_records} mock PDS records...")

    for _ in range(num_records):
        sex = random.choice(['Male', 'Female'])
        first_name = fake.first_name_male() if sex == 'Male' else fake.first_name_female()
        surname = fake.last_name()
        department = random.choice(DEPARTMENTS)
        
        # Build a JSON-compatible address dictionary matching your app.py logic
        addr_dict = {
            "zip_code": fake.postcode(),
            "house": fake.building_number(),
            "street": fake.street_name(),
            "village": fake.city_suffix(),
            "barangay": "Brgy. " + fake.word().title(),
            "city": fake.city(),
            "province": fake.state()
        }

        # Build a JSON-compatible work experience dictionary
        work_exp = [
            {
                "from_date": fake.date_between(start_date='-10y', end_date='-5y').strftime('%Y-%m-%d'),
                "to_date": fake.date_between(start_date='-5y', end_date='-1y').strftime('%Y-%m-%d'),
                "position_title": fake.job(),
                "department_agency": fake.company(),
                "status_of_appointment": random.choice(['Permanent', 'Contractual', 'Casual']),
                "govt_service": random.choice(['Y', 'N'])
            }
        ]

        # Define the core fields we want to realistically populate
        data_map = {
            'surname': surname,
            'first_name': first_name,
            'middle_name': fake.last_name(),
            'department': department,
            'birthdate': fake.date_of_birth(minimum_age=22, maximum_age=60).strftime('%Y-%m-%d'),
            'sex': sex,
            'civil_status': random.choice(['Single', 'Married', 'Widowed']),
            'agency_emp_num': str(fake.random_int(min=10000, max=99999)),
            'telephone_num': fake.phone_number(),
            'mobile_num': fake.phone_number(),
            'email_add': fake.company_email(),
            'res_address': json.dumps(addr_dict),
            'perm_address': json.dumps(addr_dict),
            'work_experience': json.dumps(work_exp),
            'elem_school': fake.company() + " Elementary School",
            'sec_school': fake.company() + " High School",
            'college_school': fake.company() + " University",
            'college_degree': "Bachelor of Science in " + fake.job()
        }

        # Match our data_map to the actual database columns.
        # If a column isn't in our map, fill it with a safe default ('N/A' or '[]')
        row_values = []
        for col in columns:
            if col in data_map:
                row_values.append(data_map[col])
            elif 'list' in col or col in ['civil_service_eligibility', 'voluntary_work', 'learning_and_development', 'skills_and_hobbies', 'non_academic_distinctions', 'membership_in_assoc_org']:
                row_values.append("[]")  # Empty JSON array for JSON fields
            else:
                row_values.append("N/A") # Default string for empty text fields

        placeholders = ', '.join(['?'] * len(columns))
        query = f"INSERT INTO employees ({', '.join(columns)}) VALUES ({placeholders})"

        try:
            cursor.execute(query, row_values)
        except Exception as e:
            print(f"Error inserting row: {e}")

    conn.commit()
    conn.close()
    print("Done! You can now start your Flask app to see the populated dashboard.")

if __name__ == '__main__':
    generate_mock_db(35)